function lookup(dictionary, key) {
  return String(key || "").split(".").reduce((value, part) => {
    if (value && Object.prototype.hasOwnProperty.call(value, part)) {
      return value[part];
    }

    return undefined;
  }, dictionary);
}

function interpolate(value, params) {
  if (!params) return value;
  return String(value).replace(/\{(\w+)\}/g, (_, key) =>
    params[key] === undefined || params[key] === null ? "" : String(params[key])
  );
}

function createTranslator(languageKey) {
  const dictionary = dictionaries[languageKey] || {};

  return function translate(key, fallback, params) {
    const translated = lookup(dictionary, key);
    const value = translated === undefined || translated === null || translated === ""
      ? fallback
      : translated;
    return interpolate(value === undefined || value === null ? key : value, params);
  };
}

function isRtlLanguage(languageKey) {
  return directions[languageKey] === "rtl";
}

